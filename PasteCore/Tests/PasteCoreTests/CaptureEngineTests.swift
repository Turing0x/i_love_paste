import Foundation
import Testing
@testable import PasteCore

private let device = UUID()
private let safari = SourceApp(bundleID: "com.apple.Safari", name: "Safari")

private func engine(
    paused: Bool = false,
    excluded: Set<String> = [],
    maxTextBytes: Int = 5 * 1024 * 1024
) -> CaptureEngine {
    CaptureEngine(
        settings: CaptureSettings(
            isPaused: paused,
            excludedBundleIDs: excluded,
            maxTextBytes: maxTextBytes
        ),
        deviceID: device
    )
}

private func snapshot(
    changeCount: Int = 2,
    types: Set<String> = [PasteboardTypes.utf8PlainText],
    string: String? = nil,
    rtf: Data? = nil,
    declaredSource: String? = nil
) -> PasteboardSnapshot {
    PasteboardSnapshot(
        changeCount: changeCount,
        types: types,
        string: string,
        rtf: rtf,
        declaredSourceBundleID: declaredSource
    )
}

/// Extrae el elemento de una decisión, fallando el test si fue un descarte.
private func captured(_ decision: CaptureDecision) throws -> ClipboardItem {
    guard case .capture(let item) = decision else {
        Issue.record("Se esperaba captura, llegó \(decision)")
        throw CancellationError()
    }
    return item
}

// MARK: - Descartes

@Test func sinCambioEnElContadorNoSeCaptura() {
    let decision = engine().decide(
        snapshot(changeCount: 7, string: "hola"),
        lastChangeCount: 7,
        frontmost: safari
    )
    #expect(decision == .skip(.unchanged))
}

